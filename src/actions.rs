//! Every user-facing action and the default keymap (SPEC §8).
//! Handlers are registered on the root element in `app.rs`.

use gpui::{App, KeyBinding, actions};

actions!(
    fm,
    [
        Open,
        ToggleQuickLook,
        MoveUp,
        MoveDown,
        MoveLeft,
        MoveRight,
        MoveFirst,
        MoveLast,
        PageUp,
        PageDown,
        Parent,
        ExtendUp,
        ExtendDown,
        ToggleSelect,
        SelectAll,
        InvertSelection,
        Rename,
        Trash,
        DeletePermanently,
        Copy,
        Cut,
        Paste,
        CopyPath,
        NewFile,
        NewFolder,
        Filter,
        RecursiveSearch,
        EditPath,
        NewTab,
        CloseTab,
        NextTab,
        PrevTab,
        ToggleGrid,
        ToggleHidden,
        SortMenu,
        TogglePreview,
        GoBack,
        GoForward,
        GoHome,
        GoDots,
        GoTrash,
        KeyHints,
        ToggleFullscreen,
        Cancel,
        Refresh,
        NextTheme,
        Quit,
    ]
);

/// Context in which single-letter keys are live: the app is focused and no text field is.
const LIST: Option<&str> = Some("Fm && !TextInput");
/// Chords that are safe even while a text field has focus.
const ANY: Option<&str> = Some("Fm");
const QL: Option<&str> = Some("Fm && QuickLook && !TextInput");

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("enter", Open, LIST),
        KeyBinding::new("l", Open, LIST),
        KeyBinding::new("space", ToggleQuickLook, LIST),
        KeyBinding::new("up", MoveUp, LIST),
        KeyBinding::new("k", MoveUp, LIST),
        KeyBinding::new("down", MoveDown, LIST),
        KeyBinding::new("j", MoveDown, LIST),
        KeyBinding::new("left", MoveLeft, LIST),
        KeyBinding::new("right", MoveRight, LIST),
        KeyBinding::new("home", MoveFirst, LIST),
        KeyBinding::new("end", MoveLast, LIST),
        KeyBinding::new("pageup", PageUp, LIST),
        KeyBinding::new("pagedown", PageDown, LIST),
        KeyBinding::new("h", Parent, LIST),
        KeyBinding::new("-", Parent, LIST),
        KeyBinding::new("backspace", Parent, LIST),
        KeyBinding::new("shift-up", ExtendUp, LIST),
        KeyBinding::new("shift-down", ExtendDown, LIST),
        KeyBinding::new("insert", ToggleSelect, LIST),
        KeyBinding::new("ctrl-a", SelectAll, LIST),
        KeyBinding::new("r", Rename, LIST),
        KeyBinding::new("f2", Rename, LIST),
        KeyBinding::new("d", Trash, LIST),
        KeyBinding::new("delete", Trash, LIST),
        KeyBinding::new("shift-d", DeletePermanently, LIST),
        KeyBinding::new("shift-delete", DeletePermanently, LIST),
        KeyBinding::new("y", Copy, LIST),
        KeyBinding::new("x", Cut, LIST),
        KeyBinding::new("p", Paste, LIST),
        KeyBinding::new("ctrl-c", CopyPath, QL),
        KeyBinding::new("/", Filter, LIST),
        KeyBinding::new("ctrl-/", RecursiveSearch, ANY),
        KeyBinding::new("ctrl-l", EditPath, ANY),
        KeyBinding::new("ctrl-t", NewTab, ANY),
        KeyBinding::new("ctrl-w", CloseTab, ANY),
        KeyBinding::new("ctrl-tab", NextTab, ANY),
        KeyBinding::new("ctrl-shift-tab", PrevTab, ANY),
        KeyBinding::new("v", ToggleGrid, LIST),
        KeyBinding::new(".", ToggleHidden, LIST),
        KeyBinding::new("s", SortMenu, LIST),
        KeyBinding::new("z", TogglePreview, LIST),
        KeyBinding::new("alt-left", GoBack, ANY),
        KeyBinding::new("alt-right", GoForward, ANY),
        KeyBinding::new("g h", GoHome, LIST),
        KeyBinding::new("g d", GoDots, LIST),
        KeyBinding::new("g t", GoTrash, LIST),
        KeyBinding::new("?", KeyHints, LIST),
        KeyBinding::new("shift-/", KeyHints, LIST),
        KeyBinding::new("f", ToggleFullscreen, QL),
        KeyBinding::new("escape", Cancel, ANY),
        KeyBinding::new("f5", Refresh, ANY),
        KeyBinding::new("ctrl-r", Refresh, ANY),
        KeyBinding::new("ctrl-shift-t", NextTheme, ANY),
        KeyBinding::new("ctrl-q", Quit, ANY),
    ]);
    crate::text_input::bind_keys(cx);
}
